package com.hbmspace.blocks.machine;

import com.hbm.blocks.machine.FieldDisturberBlock;
import com.hbm.handler.radiation.RadiationSystemNT;
import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;

public class TrollDisturberBlock extends FieldDisturberBlock {
    public static final double ABSORB = 10_000_000D;

    public TrollDisturberBlock(Properties props) {
        super(props);
    }

    @Override
    protected void onPlace(
            BlockState state,
            Level level,
            BlockPos pos,
            BlockState oldState,
            boolean movedByPiston) {
        super.onPlace(state, level, pos, oldState, movedByPiston);
        if (level instanceof ServerLevel server) {
            RadiationSystemNT.setRadForCoord(
                    server, pos, RadiationSystemNT.getRadForCoord(server, pos) - ABSORB);
        }
    }
}
