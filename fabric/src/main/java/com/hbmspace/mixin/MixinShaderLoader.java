package com.hbmspace.mixin;

import com.hbmspace.client.fog.VoxyFogShaderPatch;
import me.cortex.voxy.client.core.gl.shader.ShaderLoader;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(value = ShaderLoader.class, remap = false)
public abstract class MixinShaderLoader {
    @Inject(method = "parse", at = @At("RETURN"), cancellable = true)
    private static void hbmspace$expFog(String id, CallbackInfoReturnable<String> cir) {
        if (id.equals("voxy:post/blit_texture_depth_cutout.frag")) {
            cir.setReturnValue(VoxyFogShaderPatch.patch(cir.getReturnValue()));
        }
    }
}
